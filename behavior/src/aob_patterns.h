// ============================================================================
//  aob_patterns.h  ——  特征码表
//
//  全部特征码都是从**运行中的真实进程** dump 出来的（PVZ 1.0.0.1051-zh，
//  PlantsVsZombies.exe 3007800 字节，BaseAddress 0x00400000）。
//  相对跳转的位置一律通配成 ??，避免换了机器因代码布局微调而失配。
//
//  ## 四条符号各自要解决什么问题
//
//    AOB_PEA_UPDATE    每帧对每颗豌豆调一次 -> **抛物线积分挂这里**
//    AOB_ADD_PEA       生成豌豆对象        -> 判空枪、改伤害、取植物坐标
//    AOB_PLANT_UPDATE  植物每帧更新        -> 数"连空次数"、触发红温
//    AOB_ZOMBIE_UPDATE 僵尸每帧移动        -> 逃生状态 10 倍速
//
//  ## 已确认的地址（本机实测，仅供对照，代码里不硬编码）
//
//    0x006A9EC0  gLawnApp        ★已静态证实（见 HANDOFF §0.1）
//    LawnApp+0x768   mBoard
//    LawnApp+0x7F8   mGameMode
//    Board+0x08C     mApp
//    sizeof(Board)   0x57000
//
//    0x00520B30  Board 物件分发循环入口
//    0x00520C20  分发回调（链表迭代器用），cmp [esi+8],9 后转发 0x520AC0
//    0x00520AC0  ★不是 Pea::Update！它是「校验格子占位 -> 用自己坐标生成子弹」
//    0x0051F2A0  ★不是 AddPea！它是 Board::ProcessXxx(type) 四参数分发器
//    0x0051EA30  0x51F2A0 下面的叶子函数（被条件分发挡着）
//
//  ## ⚠ 这三条链在冒险模式下全部不生效
//
//    0x415D99:  cmp [mApp+0x7F8], 0x2B
//    0x415DA6:  jne skip
//    0x415DAE:  call 0x520B30        ← 只有 mGameMode==0x2B 才走
//
//    也就是说 0x520B30 -> 0x520C20 -> 0x520AC0 整条链被模式门住。
//    实测「三条钩子零命中」的真正原因就是这个，不是特征码找错了。
//    要钩抛射物，先用 behavior/tools/probe.py 把抛射物数组的偏移量出来。
//
//  ## 校验特征码是否唯一
//
//  注入器会打印每条特征码的命中数量。命中 > 1 说明不够独特，
//  要再往后多抄几个字节固定住。
// ============================================================================

