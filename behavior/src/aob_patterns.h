// ---------------------------------------------------------------------------
// 【主战场】抛射物主更新 —— 0x0051FCD0
//
//   55 8B EC 83 E4 F8                       push ebp / mov ebp,esp / align
//   81 EC BC 02 00 00                       sub esp,0x2BC
//   53 8B 5D 0C                             push ebx / mov ebx,[ebp+12]  ← 对象
//   D9 43 2C                                fld dword [ebx+0x2C]
//   56 D9 5C 24 1C 57                       push esi / fstp / push edi
//   D9 43 30 D9 5C 24 24                    fld dword [ebx+0x30] / fstp
//   D9 43 24 D9 5C 24 14                    fld dword [ebx+0x24]  ← x
//   D9 43 28 D9 5C 24 1C                    fld dword [ebx+0x28]  ← y
//
//   入口一次取齐四个浮点（+0x24 x / +0x28 y / +0x2C / +0x30），是抛射物
//   轨迹计算的特征。尾部 `mov esp,ebp / pop ebp / ret 8` = __stdcall 双参数。
//
//   ⚠ 不要再用 0x00520AC0 / 0x00520500：它们的外层调用点 @0x00415DAE
//     前面有 `cmp [eax+0x7F8],43 / jne` 的门，冒险模式走不到（实测零命中）。
// ---------------------------------------------------------------------------
#define AOB_PEA_MAIN_UPDATE \
    "55 8B EC 83 E4 F8 81 EC BC 02 00 00 53 8B 5D 0C D9 43 2C 56 D9 5C 24 1C 57 D9 43 30 D9 5C 24 24 D9 43 24 D9 5C 24 14 D9 43 28"

