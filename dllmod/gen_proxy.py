#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_proxy.py —— 生成 wsock32.dll 代理层

为什么要代理 wsock32.dll：
  PVZ 1.0.0.1051 的导入表里有 WSOCK32.dll（没有 version.dll / dsound.dll），
  而 wsock32 不在 KnownDLLs 里，所以「游戏目录里放一个同名 dll」能抢在系统目录前面被加载。
  这是让代码在**游戏进程内**跑起来、又不用改 exe 的最省事办法。

做法：
  1. 把 C:\\Windows\\SysWOW64\\wsock32.dll 复制成游戏目录下的 wsock32_orig.dll
  2. 我们编译出一个同名 wsock32.dll，导出表里每一条都 **转发** 给 wsock32_orig
     （PE 的 forwarder 机制：`名字 = 模块.函数`，加载器自己去加载那个模块）
  3. 我们的 DllMain 在加载时起一个线程，跑海克斯逻辑

用法：
  python gen_proxy.py            # 生成 gen/proxy.def
  python gen_proxy.py --check    # 只统计导出数量
"""

import argparse
import os
import struct
import sys

SYS32 = r"C:\Windows\SysWOW64"          # 32 位系统目录（游戏是 32 位）
TARGET = "wsock32.dll"
ORIG_NAME = "wsock32_orig"

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "gen")


def read_exports(path):
    """返回 [(name_or_None, ordinal)]。"""
    d = open(path, "rb").read()
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    optsz = struct.unpack_from("<H", d, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", d, opt)[0]
    ddoff = opt + (96 if magic == 0x10B else 112)
    exp_rva = struct.unpack_from("<I", d, ddoff)[0]

    sec0 = pe + 24 + optsz
    secs = []
    for i in range(nsec):
        o = sec0 + i * 40
        vs, va, rs, ro = struct.unpack_from("<4I", d, o + 8)
        secs.append((va, rs, ro))

    def off(rva):
        for va, rs, ro in secs:
            if va <= rva < va + rs:
                return ro + (rva - va)
        return None

    if not exp_rva:
        return []
    eo = off(exp_rva)
    nfuncs = struct.unpack_from("<I", d, eo + 20)[0]
    nnames = struct.unpack_from("<I", d, eo + 24)[0]
    funcs_rva = struct.unpack_from("<I", d, eo + 28)[0]
    names_rva = struct.unpack_from("<I", d, eo + 32)[0]
    ords_rva = struct.unpack_from("<I", d, eo + 36)[0]
    base_ord = struct.unpack_from("<I", d, eo + 16)[0]

    fo = off(funcs_rva)
    no = off(names_rva)
    oo = off(ords_rva)

    named = {}
    for i in range(nnames):
        nr = struct.unpack_from("<I", d, no + i * 4)[0]
        p = off(nr)
        nm = d[p:d.index(b"\0", p)].decode("latin1")
        idx = struct.unpack_from("<H", d, oo + i * 2)[0]
        named[idx] = nm

    out = []
    for i in range(nfuncs):
        fn_rva = struct.unpack_from("<I", d, fo + i * 4)[0]
        if fn_rva == 0:
            continue
        out.append((named.get(i), base_ord + i))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--sys32", default=SYS32)
    args = ap.parse_args()

    src = os.path.join(args.sys32, TARGET)
    if not os.path.exists(src):
        raise SystemExit("找不到 %s" % src)

    exps = read_exports(src)
    named = [e for e in exps if e[0]]
    anon = [e for e in exps if not e[0]]
    print("%s: 共 %d 条导出，具名 %d，仅序号 %d"
          % (TARGET, len(exps), len(named), len(anon)))
    if anon:
        print("  仅序号的：", [o for _, o in anon][:20])

    if args.check:
        return

    os.makedirs(GEN, exist_ok=True)
    path = os.path.join(GEN, "proxy.def")
    with open(path, "w", encoding="ascii", newline="\r\n") as f:
        f.write("; auto-generated by gen_proxy.py -- do not edit\n")
        f.write("LIBRARY %s\n" % TARGET)
        f.write("EXPORTS\n")
        for nm, ordv in exps:
            if nm:
                f.write("    %s = %s.%s @%d\n" % (nm, ORIG_NAME, nm, ordv))
            else:
                # 只有序号的，用序号转发
                f.write("    anon%d = %s.#%d @%d\n" % (ordv, ORIG_NAME, ordv, ordv))
    print("写出 %s（%d 行导出）" % (path, len(exps)))


if __name__ == "__main__":
    main()
